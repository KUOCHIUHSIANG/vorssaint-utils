import Foundation

struct RGBLightingFeatureStrings {
    let title: String
    let hubDescription: String
    let panelDescription: String
    let showInPanel: String
    let lighting: String
    let off: String
    let cycle: String
    let wave: String
    let solid: String
    let breathing: String
    let rainbowBreathing: String
    let meteor: String
    let lightning: String
    let lightningHint: String
    let screen: String
    let screenHint: String
    let screenPermission: String
    let allowPermission: String
    let screenFailed: String
    let music: String
    let musicRainbow: String
    let screenMusic: String
    let musicHint: String
    let direction: String
    let directionDown: String
    let directionUp: String
    let directionRight: String
    let directionLeft: String
    let color: String
    let brightness: String
    let speed: String
    let addColor: String
    let deleteColor: String
    let deleteHint: String
    let caption: String
    let devices: String
    let connected: String
    let notConnected: String
    let unsupportedFormat: String
    let noAnswer: String
    let monitor: String

    func modeName(_ mode: RGBLightingMode) -> String {
        switch mode {
        case .off: return off
        case .solid: return solid
        case .breathing: return breathing
        case .cycle: return cycle
        case .rainbowBreathing: return rainbowBreathing
        case .wave: return wave
        case .meteor: return meteor
        case .lightning: return lightning
        case .screen: return screen
        case .music: return music
        case .musicRainbow: return musicRainbow
        case .screenMusic: return screenMusic
        }
    }

    func directionName(_ direction: RGBWaveDirection) -> String {
        switch direction {
        case .down: return directionDown
        case .up: return directionUp
        case .right: return directionRight
        case .left: return directionLeft
        }
    }
}

extension FeatureStrings {
    static func rgbLighting(_ language: AppLanguage) -> RGBLightingFeatureStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .uk: return .uk
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        }
    }
}

